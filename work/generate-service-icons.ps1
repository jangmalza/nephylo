$ErrorActionPreference = 'Stop'
$assetDirectory = Join-Path $PSScriptRoot 'assets/service-icons'
$definitions = foreach ($id in @('codex','eleven','openai','claude','gemini','cursor','higgsfield','higgsfield-api')) {
    $filename = if ($id -eq 'eleven') { 'elevenlabs' } elseif ($id -eq 'higgsfield-api') { 'higgsfield' } else { $id }
    [xml]$svg = [IO.File]::ReadAllText((Join-Path $assetDirectory ($filename + '.svg')))
    $paths = @($svg.SelectNodes('/*[local-name()="svg"]/*[local-name()="path"]'))
    if ($svg.DocumentElement.GetAttribute('viewBox') -ne '0 0 24 24' -or $paths.Count -ne 1) { throw "Unsupported icon format: $id" }
    $geometry = $paths[0].GetAttribute('d')
    if ($geometry -notmatch '^[MmZzLlHhVvCcSsQqTtAaEe0-9+.,\s-]+$') { throw "Invalid icon geometry: $id" }
    '            { "' + $id + '", Create("' + $geometry + '") },'
}
$header = @'
// Generated by generate-service-icons.ps1 from the pinned SVG originals in assets/service-icons.
// LobeHub Lobe Icons, MIT. See THIRD-PARTY-NOTICES.txt and assets/service-icons/SOURCES.txt.
// Higgsfield entries use an original H monogram, not an official brand logo.
using System;
using System.Collections.Generic;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Markup;
using System.Windows.Media;

namespace UsageWidget
{
    public sealed class ServiceChoice
    {
        public string Name { get; private set; }
        public ImageSource Icon { get; private set; }
        public ServiceChoice(string id, string name) { Name = name; Icon = ServiceIcons.Get(id); }
        public override string ToString() { return Name; }
    }

    internal static class ServiceIcons
    {
        private static readonly Dictionary<string, ImageSource> Icons = new Dictionary<string, ImageSource> {
'@
$footer = @'
        };

        internal static ImageSource Get(string id)
        {
            ImageSource image; return Icons.TryGetValue(id ?? String.Empty,out image) ? image : null;
        }

        private static DrawingImage Create(string path)
        {
            var geometry = Geometry.Parse("F0 " + path); geometry.Freeze();
            var bounds = new RectangleGeometry(new Rect(0,0,24,24)); bounds.Freeze();
            var ink = WidgetPalette.Brush("#2448F5");
            var drawing = new DrawingGroup { ClipGeometry = bounds };
            // Preserve each logo's original whitespace and aspect ratio in a common 24px viewport.
            drawing.Children.Add(new GeometryDrawing(Brushes.Transparent,null,bounds));
            drawing.Children.Add(new GeometryDrawing(ink,null,geometry));
            return new DrawingImage(drawing);
        }

        internal static DataTemplate ChoiceTemplate()
        {
            return (DataTemplate)XamlReader.Parse(@"<DataTemplate xmlns='http://schemas.microsoft.com/winfx/2006/xaml/presentation'>
                <StackPanel Orientation='Horizontal'>
                    <Image Source='{Binding Icon}' Width='18' Height='18' Stretch='Uniform' Margin='0,0,9,0' VerticalAlignment='Center' IsHitTestVisible='False'/>
                    <TextBlock Text='{Binding Name}' VerticalAlignment='Center'/>
                </StackPanel>
            </DataTemplate>");
        }
    }
}
'@
$source = $header + [Environment]::NewLine + ($definitions -join [Environment]::NewLine) + [Environment]::NewLine + $footer
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'src/ServiceIcons.cs'),$source,[Text.UTF8Encoding]::new($false))
Write-Output 'Generated eight embedded service icons.'
